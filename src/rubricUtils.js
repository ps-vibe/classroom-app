// คำอธิบายระดับของเกณฑ์ "ตรงต่อเวลา" สร้างจากจำนวนวันที่ตั้งไว้
export function lateText(lateDays, level) {
  const [a, b, c] = lateDays;
  if (level === 4) return a === 0 ? "ส่งตรงกำหนด" : `ส่งช้าไม่เกิน ${a} วัน`;
  if (level === 3) return a + 1 === b ? `ส่งช้า ${b} วัน` : `ส่งช้า ${a + 1}-${b} วัน`;
  if (level === 2) return b + 1 === c ? `ส่งช้า ${c} วัน` : `ส่งช้า ${b + 1}-${c} วัน`;
  return `ส่งช้ากว่า ${c} วัน`;
}

export function levelFromLateDays(lateDays, daysLate) {
  const [a, b, c] = lateDays;
  if (daysLate <= a) return 4;
  if (daysLate <= b) return 3;
  if (daysLate <= c) return 2;
  return 1;
}

